// Design tokens from the WolOS site (I8): the hub takes its colours, type scale, radii and fonts from a
// pinned copy of the site's public/brand/colors.css and the token blocks of its src/index.css, so the
// two never drift and the hub never forks the look. Writes src/tokens.css with the site commit in its
// header, copies the mark and the favicons, and keeps the site's name list for check-doctrine.
//
//   node scripts/sync-tokens.mjs           copy from the site checkout (WOLOS_SITE, or ../../../site)
//   node scripts/sync-tokens.mjs --check   fail when src/tokens.css differs from what the site has now;
//                                          without a site checkout (Pages, a clean clone) only the
//                                          committed file's shape is checked
//
// Taken from src/index.css: the light block for a light choice on a dark system, the dark marker, the
// @theme block (as plain custom properties; the hub has no Tailwind) and the terminal colours. Nothing
// else: the hub's own rules (src/hub.css) may only read these variables (scripts/check-theme.mjs).
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(HERE, "src/tokens.css");
const SITE = resolve(process.env.WOLOS_SITE || resolve(HERE, "../../../site"));
const check = process.argv.includes("--check");
const read = (p) => readFileSync(p, "utf8").replace(/\r\n?/g, "\n");

/** The block that starts at the first match of `start` (a regexp), braces balanced. */
function block(css, start, what) {
  const m = start.exec(css);
  if (!m) throw new Error(`sync-tokens: ${what} not found in the site's src/index.css`);
  let depth = 0;
  for (let i = css.indexOf("{", m.index); i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return css.slice(m.index, i + 1);
  }
  throw new Error(`sync-tokens: ${what} is not closed`);
}

function build(siteDir) {
  const colors = read(resolve(siteDir, "public/brand/colors.css")).trim();
  const index = read(resolve(siteDir, "src/index.css"));
  const light = block(index, /^:root\[data-theme="light"\]\s*\{/m, "the light block");
  const dark = block(index, /^:root\[data-theme="dark"\]\s*\{/m, "the dark marker");
  const theme = block(index, /^@theme\s*\{/m, "the @theme block").replace(/^@theme\s*\{/, ":root {");
  const term = block(index, /^:root\s*\{\s*--term-bg/m, "the terminal colours");
  let commit = "unknown";
  try { commit = execFileSync("git", ["-C", siteDir, "rev-parse", "HEAD"], { encoding: "utf8" }).trim(); } catch { /* not a checkout */ }
  const body = [
    "/* public/brand/colors.css */", colors, "",
    "/* src/index.css: light choice on a dark system, dark marker */", light, dark, "",
    "/* src/index.css @theme: the one type scale, fonts and the short colour names */", theme, "",
    "/* src/index.css: terminal surface */", term, "",
  ].join("\n");
  return { commit, body };
}

const HEADER = (commit) => `/* Generated by scripts/sync-tokens.mjs from wonderlandos/site commit ${commit}. Do not edit: run npm run sync. */\n`;
const bodyOf = (text) => text.replace(/^\/\* Generated by [^\n]*\n/, "");

if (!existsSync(resolve(SITE, "public/brand/colors.css"))) {
  if (!check) { console.error(`sync-tokens: no site checkout at ${SITE} (set WOLOS_SITE)`); process.exit(1); }
  const have = existsSync(OUT) ? read(OUT) : "";
  const m = /^\/\* Generated by scripts\/sync-tokens\.mjs from wonderlandos\/site commit ([0-9a-f]{40}|unknown)\./.exec(have);
  if (!m || !/--wol-accent:/.test(have) || !/--text-3xl:/.test(have)) { console.error("sync-tokens: src/tokens.css is missing or not generated"); process.exit(1); }
  console.log(`sync-tokens: no site checkout; the committed tokens (site ${m[1].slice(0, 12)}) are used`);
  process.exit(0);
}

const { commit, body } = build(SITE);
if (check) {
  const have = existsSync(OUT) ? read(OUT) : "";
  if (bodyOf(have) !== body) { console.error(`sync-tokens: src/tokens.css differs from the site at ${commit.slice(0, 12)}: run npm run sync`); process.exit(1); }
  const pinned = /commit ([0-9a-f]+|unknown)/.exec(have)?.[1];
  console.log(`sync-tokens: tokens match the site${pinned !== commit ? ` (pinned ${pinned?.slice(0, 12)}, site now ${commit.slice(0, 12)}, same tokens)` : ` at ${commit.slice(0, 12)}`}`);
} else {
  writeFileSync(OUT, HEADER(commit) + body);
  for (const f of ["wolos-mark.svg", "favicon.svg", "favicon-32.png", "apple-touch-icon.png"]) copyFileSync(resolve(SITE, "public", f), resolve(HERE, "public", f));
  copyFileSync(resolve(SITE, "data/doctrine.json"), resolve(HERE, "data/doctrine.json"));
  console.log(`sync-tokens: src/tokens.css from the site at ${commit.slice(0, 12)}; mark, favicons and the name list copied`);
}
